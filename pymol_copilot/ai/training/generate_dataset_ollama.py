"""Automated dataset generation via a local Ollama service.

This script reads the prompt batch files produced by::

    python generate_dataset.py --mode generate_prompts ...

and submits each file to a local Ollama API endpoint, saving the model's
response as a matching ``.response.txt`` file. Those response files are
then consumed by::

    python generate_dataset.py --mode collect_responses ...

Prerequisites
-------------
Make sure Ollama is installed and running locally. Start the server and pull
the desired model (e.g. qwen2.5:1.5b-instruct)::

    ollama pull qwen2.5:1.5b-instruct

Usage
-----
.. code-block:: bash

    # Use default model (qwen2.5:1.5b-instruct) and default URL (http://localhost:11434)
    python generate_dataset_ollama.py --prompts_dir data/prompts/

    # Use custom Ollama endpoint and model
    python generate_dataset_ollama.py \\
        --prompts_dir data/prompts/ \\
        --url http://192.168.1.100:11434 \\
        --model llama3:8b

    # Dry run — print prompts without calling the local service
    python generate_dataset_ollama.py \\
        --prompts_dir data/prompts/ \\
        --dry_run
"""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import sys
import time
import urllib.error
import urllib.request


def _call_ollama_api_with_retry(
    url: str,
    model_name: str,
    prompt: str,
    max_retries: int = 5,
    backoff_base: float = 2.0,
) -> str:
    """Submit a prompt to the local Ollama API with exponential back-off.

    Args:
      url: Ollama API base URL (e.g. "http://localhost:11434").
      model_name: Name of the model to use in Ollama.
      prompt: Standalone prompt string.
      max_retries: Maximum retry attempts on transient errors.
      backoff_base: Initial delay in seconds for back-off.

    Returns:
      The response string generated by the model.

    Raises:
      SystemExit: If the request fails after maximum retries.
    """
    endpoint = f"{url.rstrip('/')}/api/generate"
    payload = {
        "model": model_name,
        "prompt": prompt,
        "stream": False,
        "options": {
            "temperature": 0.9,
            "top_p": 0.95,
            "num_predict": 8192,
        },
    }
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        endpoint,
        data=data,
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    delay = backoff_base
    for attempt in range(1, max_retries + 1):
        try:
            with urllib.request.urlopen(req, timeout=300) as response:
                resp_data = json.loads(response.read().decode("utf-8"))
                if "response" in resp_data:
                    return str(resp_data["response"])
                print(
                    f"[ERROR] Ollama response did not contain 'response' key: "
                    f"{resp_data}",
                    file=sys.stderr,
                )
                sys.exit(1)
        except (
            urllib.error.HTTPError,
            urllib.error.URLError,
            Exception,
        ) as exc:
            if attempt == max_retries:
                print(
                    f"[ERROR] Ollama API call failed (attempt {attempt}/{max_retries}): "
                    f"{exc}",
                    file=sys.stderr,
                )
                sys.exit(1)
            print(
                f"[WARNING] Transient error calling Ollama (attempt {attempt}): {exc}\n"
                f"  Backing off {delay:.1f}s before retry ..."
            )
            time.sleep(delay)
            delay = min(delay * 2.0, 60.0)

    sys.exit(1)


def _discover_batches(prompts_dir: pathlib.Path) -> list[pathlib.Path]:
    """Return all prompt batch files, sorted by name.

    Matches both the new-style categorised names (``batch_pos_NNN.txt``,
    ``batch_neg_NNN.txt``) and legacy mixed names (``batch_NNN.txt``).

    Args:
      prompts_dir: Directory containing prompt batch ``.txt`` files.

    Returns:
      Sorted list of ``.txt`` batch file paths.

    Raises:
      SystemExit: If no batch files are found.
    """
    patterns = [
        "batch_pos_*.txt",
        "batch_neg_*.txt",
        "batch_[0-9]*.txt",
    ]
    found: list[pathlib.Path] = []
    for pattern in patterns:
        found.extend(prompts_dir.glob(pattern))

    found = [p for p in found if not p.name.endswith(".response.txt")]

    if not found:
        print(
            f"[ERROR] No prompt batch files found in {prompts_dir}.\n"
            "Run generate_dataset.py --mode generate_prompts first.",
            file=sys.stderr,
        )
        sys.exit(1)

    return sorted(set(found), key=lambda p: p.name)


def _response_path(batch_file: pathlib.Path) -> pathlib.Path:
    """Return the expected response file path for a given batch file.

    The naming convention is ``<stem>.response.txt`` alongside the
    batch file. This is the format expected by
    ``generate_dataset.py --mode collect_responses``.

    Args:
      batch_file: Path to a batch prompt ``.txt`` file.

    Returns:
      Sibling ``.response.txt`` path.
    """
    return batch_file.with_suffix(".response.txt")


def _process_batches(
    batches: list[pathlib.Path],
    url: str,
    model_name: str,
    resume: bool,
    dry_run: bool,
    min_delay_seconds: float,
) -> None:
    """Process each batch file, calling Ollama and saving responses.

    Each batch file content is submitted as a single prompt. The model's
    response is written to ``<batch_stem>.response.txt`` in the same
    directory. Already-completed files are skipped when ``resume=True``.

    Args:
      batches: Ordered list of batch ``.txt`` file paths.
      url: Ollama API base URL.
      model_name: Name of the model to run.
      resume: If ``True``, skip batches that already have a response file.
      dry_run: If ``True``, print prompts but do not call the API.
      min_delay_seconds: Minimum sleep between consecutive requests.

    Raises:
      SystemExit: If a request fails or is interrupted.
    """
    total = len(batches)
    count = 0
    last_request_time: float = 0.0

    for idx, batch_file in enumerate(batches, start=1):
        resp_file = _response_path(batch_file)

        if resume and resp_file.exists():
            print(
                f"[{idx:3d}/{total}] SKIP (response exists): {batch_file.name}"
            )
            continue

        prompt = batch_file.read_text(encoding="utf-8")

        if dry_run:
            print(
                f"[{idx:3d}/{total}] DRY RUN — would send {batch_file.name} "
                f"({len(prompt)} chars)"
            )
            continue

        elapsed = time.monotonic() - last_request_time
        wait = min_delay_seconds - elapsed
        if wait > 0:
            time.sleep(wait)

        print(
            f"[{idx:3d}/{total}] Sending {batch_file.name} "
            f"({len(prompt)} chars) to Ollama ...",
            end="",
            flush=True,
        )
        t0 = time.monotonic()
        last_request_time = t0

        response_text = _call_ollama_api_with_retry(
            url=url, model_name=model_name, prompt=prompt
        )
        elapsed_call = time.monotonic() - t0
        count += 1

        resp_file.write_text(response_text, encoding="utf-8")
        print(f" done in {elapsed_call:.1f}s [session total: {count}]")

    if not dry_run and batches:
        print(
            f"\n[generate_dataset_ollama] All batches processed.\n"
            f"  Requests this session : {count}\n"
            f"  Response files in     : {batches[0].parent}\n"
            f"\nNext step:\n"
            f"  python generate_dataset.py \\\n"
            f"      --mode collect_responses \\\n"
            f"      --input_dir {batches[0].parent} \\\n"
            f"      --output_dir <your_data_dir>/"
        )


def _parse_args() -> argparse.Namespace:
    """Parse command-line arguments.

    Returns:
      Parsed argument namespace.
    """
    parser = argparse.ArgumentParser(
        description=(
            "Generate cBioMOL training data via a local Ollama API. "
            "Reads batch_*.txt files and writes batch_*.response.txt."
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--prompts_dir",
        type=pathlib.Path,
        default=pathlib.Path("data/prompts"),
        help="Directory containing batch_*.txt prompt files.",
    )
    parser.add_argument(
        "--url",
        default="http://localhost:11434",
        help="Base URL of the local Ollama service.",
    )
    parser.add_argument(
        "--model",
        default="qwen2.5:1.5b-instruct",
        help="Ollama model name to use for generation.",
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        default=True,
        help=(
            "Skip batch files that already have a matching .response.txt. "
            "Enabled by default — use --no_resume to force re-processing."
        ),
    )
    parser.add_argument(
        "--no_resume",
        dest="resume",
        action="store_false",
        help="Re-process all batches even if a response file already exists.",
    )
    parser.add_argument(
        "--dry_run",
        action="store_true",
        help=(
            "Print what would be sent to the API without making any actual "
            "calls. Useful for inspecting prompts before running."
        ),
    )
    parser.add_argument(
        "--max_batches",
        type=int,
        default=0,
        help=(
            "Process at most this many batches (0 = no limit). "
            "Useful for small test runs."
        ),
    )
    parser.add_argument(
        "--delay",
        type=float,
        default=0.0,
        help="Minimum delay in seconds between requests to avoid overloading.",
    )
    return parser.parse_args()


def main() -> None:
    """Entry point for the Ollama dataset generation script.

    Raises:
      SystemExit: If the prompts directory does not exist.
    """
    args = _parse_args()

    print(
        f"[generate_dataset_ollama] Starting\n"
        f"  Ollama URL     : {args.url}\n"
        f"  Model          : {args.model}\n"
        f"  Prompts dir    : {args.prompts_dir}\n"
        f"  Resume         : {args.resume}\n"
        f"  Dry run        : {args.dry_run}\n"
        f"  Min delay      : {args.delay}s between requests"
    )

    if not args.prompts_dir.is_dir():
        print(
            f"[ERROR] prompts_dir does not exist: {args.prompts_dir}",
            file=sys.stderr,
        )
        sys.exit(1)

    batches = _discover_batches(args.prompts_dir)

    if args.max_batches > 0:
        batches = batches[: args.max_batches]

    print(
        f"  Batches found  : {len(batches)}"
        + (f" (capped at {args.max_batches})" if args.max_batches else "")
    )

    _process_batches(
        batches=batches,
        url=args.url,
        model_name=args.model,
        resume=args.resume,
        dry_run=args.dry_run,
        min_delay_seconds=args.delay,
    )


if __name__ == "__main__":
    main()
